--------------------------------------------------------------------------------
-- 1. DDL: Create Partitioned Raw Events Table
--------------------------------------------------------------------------------

DROP TABLE IF EXISTS raw_events CASCADE;

CREATE TABLE raw_events (
    event_time    TIMESTAMPTZ NOT NULL,
    event_type    VARCHAR(30) NOT NULL, -- 'view', 'cart', 'remove_from_cart', 'purchase'
    product_id    BIGINT NOT NULL,
    category_id   BIGINT,
    category_code VARCHAR(255),
    brand         VARCHAR(255),
    price         NUMERIC(10, 2) CHECK (price >= 0),
    user_id       BIGINT NOT NULL,
    user_session  UUID
) PARTITION BY RANGE (event_time);

-- Comments on table columns
COMMENT ON TABLE raw_events IS 'Partitioned clickstream event store for e-commerce user behavior';
COMMENT ON COLUMN raw_events.event_time IS 'Timestamp of the event (with timezone)';
COMMENT ON COLUMN raw_events.event_type IS 'Action type: view, cart, remove_from_cart, purchase';
COMMENT ON COLUMN raw_events.user_id IS 'Unique user identification number';
COMMENT ON COLUMN raw_events.user_session IS 'Raw clickstream session UUID generated by frontend';

--------------------------------------------------------------------------------
